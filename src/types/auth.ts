export type UserType = 'Familiar' | 'Associado' | 'Jovem produtor' | 'Mulher chefe de família' | 'Extensionista';

export type DistrictZone = 
  | 'Homoíne-Sede'
  | 'Maculuve'
  | 'Nhanombe'
  | 'Inhambane-Cidade'
  | 'Maxixe'
  | 'Massinga'
  | 'Outra zona de Homoíne';

export type CropType = 
  | 'Mandioca'
  | 'Milho'
  | 'Amendoim'
  | 'Feijão nhemba'
  | 'Mapira'
  | 'Caju'
  | 'Hortícolas'
  | 'Batata-doce'
  | 'Gergelim'
  | 'Banana'
  | 'Coco'
  | 'Feijão boer'
  | 'Outra';

export type SocialProvider = 'google' | 'apple' | 'whatsapp' | 'gov';

export interface User {
  id: string;
  name: string;
  phone: string;
  email: string;
  zone: DistrictZone;
  crop: CropType;
  type: UserType;
  password?: string;
  plan: 'Gratuita' | 'Premium';
  createdAt: string;
  twoFactorEnabled: boolean;
  twoFactorSecret?: string;
  biometricRegistered: boolean;
  biometricCredentialId?: string;
  biometricDeviceName?: string;
  socialProvider?: SocialProvider;
  backupCodes: string[];
  lastLoginAt?: string;
}

export interface Session {
  user: User;
  token: string;
  authenticatedWith: 'password' | 'biometric' | 'social' | '2fa';
  expiresAt: string;
}

export interface AuditLog {
  id: string;
  userId: string;
  action: string;
  timestamp: string;
  ip: string;
  device: string;
  status: 'success' | 'failed' | 'warning';
  details?: string;
}

export interface AppNotification {
  id: string;
  title: string;
  message: string;
  type: 'climate' | 'market' | 'security' | 'system';
  timestamp: string;
  read: boolean;
  actionLabel?: string;
}

export interface MarketPrice {
  crop: CropType;
  market: string;
  minPrice: number;
  maxPrice: number;
  unit: string;
  trend: 'up' | 'down' | 'stable';
  lastUpdated: string;
}

export interface TestResult {
  id: string;
  title: string;
  category: 'Segurança' | 'Biometria' | '2FA' | 'Offline' | 'Social' | 'Relatórios' | 'Clima' | 'Agronomia' | 'Finanças';
  status: 'passed' | 'failed' | 'running' | 'idle';
  durationMs: number;
  assertions: number;
  message: string;
  details?: string;
}

export type CropCycleStatus = 'planeado' | 'crescimento' | 'floracao' | 'maduro' | 'colhido';

export type CropReminderType = 
  | 'plantio' 
  | 'germinacao' 
  | 'sacha' 
  | 'adubacao' 
  | 'rega' 
  | 'fitossanitario' 
  | 'pre-colheita' 
  | 'colheita' 
  | 'pos-colheita' 
  | 'outro';

export interface CropReminder {
  id: string;
  cycleId: string;
  title: string;
  description: string;
  dueDate: string; // YYYY-MM-DD
  type: CropReminderType;
  priority: 'alta' | 'media' | 'baixa';
  completed: boolean;
  completedAt?: string;
  isAutoGenerated: boolean;
  stageOffsetDays?: number;
}

export interface CropCycle {
  id: string;
  userId: string;
  plotName: string;
  crop: CropType;
  variety?: string;
  areaHectares: number;
  plantingDate: string; // YYYY-MM-DD
  estimatedHarvestDate: string; // YYYY-MM-DD
  actualHarvestDate?: string;
  status: CropCycleStatus;
  expectedYieldKg?: number;
  notes?: string;
  createdAt: string;
  reminders: CropReminder[];
}

